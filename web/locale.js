  function translate(value) {
    const source = String(value ?? '');
    const core = source.trim();
    let result = labels.get(core);
    if (!result) for (const [pattern, format] of patterns) {
      const match = core.match(pattern);
      if (match) { result = format(...match); break; }
    }
    return result ? source.replace(core, result) : source;
  }
  function translateText(node) {
    if (node.parentElement?.closest(excluded)) return;
    const current = node.nodeValue;
    const saved = originals.get(node);
    const original = saved && current === saved.translated ? saved.original : current;
    const next = selected === 'en' ? translate(original) : original;
    originals.set(node, {original, translated: next});
    if (current !== next) node.nodeValue = next;
  }
  function translateAttributes(element) {
    if (element.matches?.(excluded) || element.closest?.(excluded)) return;
    const saved = attributeOriginals.get(element) || {};
    for (const name of ['placeholder', 'title', 'aria-label', 'alt']) {
      if (!element.hasAttribute(name)) continue;
      const current = element.getAttribute(name);
      const previous = saved[name];
      const original = previous && current === previous.translated ? previous.original : current;
      const next = selected === 'en' ? translate(original) : original;
      saved[name] = {original, translated: next};
      if (current !== next) element.setAttribute(name, next);
    }
    attributeOriginals.set(element, saved);
  }
